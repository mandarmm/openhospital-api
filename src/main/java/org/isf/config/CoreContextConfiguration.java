package org.isf.config;

import org.isf.menu.manager.Context;
import org.springframework.beans.BeansException;
import org.springframework.context.ApplicationContext;
import org.springframework.context.ApplicationContextAware;
import org.springframework.context.annotation.Configuration;

/**
 * Gives the core its {@link Context}, as the desktop client does: some core utilities find their beans through it,
 * such as the query behind the spreadsheets of reports ({@code DbQueryLogger}).
 */
@Configuration
public class CoreContextConfiguration implements ApplicationContextAware {

	@Override
	public void setApplicationContext(ApplicationContext applicationContext) throws BeansException {
		Context.setApplicationContext(applicationContext);
	}
}
